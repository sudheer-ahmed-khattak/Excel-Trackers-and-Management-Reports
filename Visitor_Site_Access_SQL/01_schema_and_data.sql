CREATE TABLE companies (
    company_id    INTEGER PRIMARY KEY,
    company_name  TEXT NOT NULL UNIQUE,
    company_type  TEXT NOT NULL CHECK (company_type IN ('Main Contractor','Client','Consultant','Subcontractor','Supplier','Service Provider'))
);

CREATE TABLE site_zones (
    zone_id            INTEGER PRIMARY KEY,
    zone_name          TEXT NOT NULL UNIQUE,
    risk_level         TEXT NOT NULL CHECK (risk_level IN ('Low','Medium','High')),
    induction_required INTEGER NOT NULL CHECK (induction_required IN (0,1)),
    ppe_required       TEXT NOT NULL
);

CREATE TABLE people (
    person_id    INTEGER PRIMARY KEY,
    full_name    TEXT NOT NULL,
    company_id   INTEGER NOT NULL REFERENCES companies(company_id),
    nationality  TEXT,
    category     TEXT NOT NULL CHECK (category IN ('Employee','Subcontractor Staff','Visitor'))
);

CREATE TABLE inductions (
    induction_id   INTEGER PRIMARY KEY,
    person_id      INTEGER NOT NULL REFERENCES people(person_id),
    induction_date TEXT NOT NULL,
    trainer        TEXT,
    score          INTEGER CHECK (score BETWEEN 0 AND 100),
    result         TEXT NOT NULL CHECK (result IN ('Pass','Fail')),
    valid_until    TEXT
);

CREATE TABLE hse_trainings (
    training_id  INTEGER PRIMARY KEY,
    person_id    INTEGER NOT NULL REFERENCES people(person_id),
    course       TEXT NOT NULL,
    completed_on TEXT NOT NULL,
    expires_on   TEXT NOT NULL
);

CREATE TABLE access_cards (
    card_no     TEXT PRIMARY KEY,
    person_id   INTEGER NOT NULL REFERENCES people(person_id),
    issue_date  TEXT NOT NULL,
    expiry_date TEXT NOT NULL,
    card_type   TEXT NOT NULL CHECK (card_type IN ('Permanent','Temporary','Visitor')),
    status      TEXT NOT NULL CHECK (status IN ('Active','Expired','Lost','Cancelled'))
);

CREATE TABLE card_zones (                -- which zones each card opens (many-to-many)
    card_no  TEXT    NOT NULL REFERENCES access_cards(card_no),
    zone_id  INTEGER NOT NULL REFERENCES site_zones(zone_id),
    PRIMARY KEY (card_no, zone_id)
);

CREATE TABLE ppe_issues (
    issue_id   INTEGER PRIMARY KEY,
    person_id  INTEGER NOT NULL REFERENCES people(person_id),
    issue_date TEXT NOT NULL,
    item       TEXT NOT NULL,
    qty        INTEGER NOT NULL CHECK (qty > 0)
);

CREATE TABLE visits (
    visit_id   INTEGER PRIMARY KEY,
    person_id  INTEGER NOT NULL REFERENCES people(person_id),
    host       TEXT NOT NULL,
    visit_date TEXT NOT NULL,
    time_in    TEXT NOT NULL,
    time_out   TEXT,                       -- NULL = still on site
    purpose    TEXT,
    zone_id    INTEGER REFERENCES site_zones(zone_id)
);

CREATE INDEX ix_cards_expiry   ON access_cards(expiry_date);
CREATE INDEX ix_visits_date    ON visits(visit_date);
CREATE INDEX ix_trainings_exp  ON hse_trainings(expires_on);


